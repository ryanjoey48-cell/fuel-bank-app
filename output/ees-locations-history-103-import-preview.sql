do $validate_seed$
declare
  source_count integer;
  unique_id_count integer;
begin
  select count(*), count(distinct id)
    into source_count, unique_id_count
  from pg_temp._ees_locations_history_seed;

  if source_count <> 103 or unique_id_count <> 103 then
    raise exception 'Expected 103 source rows with 103 unique stable IDs; found % rows and % IDs.', source_count, unique_id_count;
  end if;

  if exists (
    select 1
    from pg_temp._ees_locations_history_seed
    where nullif(btrim(company_name), '') is null
       or nullif(btrim(address), '') is null
       or verification_status <> 'needs_check'
       or verified_at is not null
       or destination_type not in ('Factory','Warehouse','Airport','Port','Customer','Depot','Other')
       or google_maps_url is null
       or google_maps_url !~* '^https://(maps\.google\.com|(www\.)?google\.(com|[a-z]{2,3}|co\.[a-z]{2}))/maps'
       or (truck_entrance_url is not null and truck_entrance_url !~* '^https://(maps\.google\.com|(www\.)?google\.(com|[a-z]{2,3}|co\.[a-z]{2}))/maps')
  ) then
    raise exception 'Seed rows failed required field, URL, or needs_check validation; import stopped.';
  end if;

  if exists (
    select 1
    from pg_temp._ees_locations_history_seed
    group by lower(regexp_replace(btrim(company_name), '[[:space:]]+', ' ', 'g')),
             lower(regexp_replace(btrim(address), '[[:space:]]+', ' ', 'g'))
