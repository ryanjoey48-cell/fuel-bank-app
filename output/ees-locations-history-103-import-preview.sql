-- Skipped/conflicting rows. An empty result means no source rows were skipped.
with outcomes as (
  select
    source.source_row,
    source.workbook_id,
    source.company_name,
    source.address,
    inserted.id as inserted_id,
    stable.id as stable_id,
    exact_pair.id as exact_pair_id
  from pg_temp._ees_locations_history_seed source
  left join pg_temp._ees_locations_history_inserted inserted on inserted.id = source.id
  left join public.ees_locations stable on stable.id = source.id
  left join lateral (
    select existing.id
    from public.ees_locations existing
    where lower(regexp_replace(btrim(existing.company_name), '[[:space:]]+', ' ', 'g')) = lower(regexp_replace(btrim(source.company_name), '[[:space:]]+', ' ', 'g'))
      and lower(regexp_replace(btrim(existing.address), '[[:space:]]+', ' ', 'g')) = lower(regexp_replace(btrim(source.address), '[[:space:]]+', ' ', 'g'))
    order by existing.id
    limit 1
  ) exact_pair on true
)
select
  source_row,
  workbook_id,
  company_name,
  address,
  case
    when stable_id is not null then 'Skipped: stable source ID already exists; existing row left unchanged'
    when exact_pair_id is not null then 'Skipped: exact company and full address already exist; existing row left unchanged'
    else 'Not inserted: inspect this record and the database state'
  end as disposition
from outcomes
where inserted_id is null
union all
select null::integer, null::text, null::text, null::text, 'No skipped or conflicting source rows'
where not exists (select 1 from outcomes where inserted_id is null)
order by source_row nulls last;

